# Writes app/theme-dark.css (see the comment it writes at the top).
# Run from anywhere: python scripts/gen-dark-css.py
import re, sys
from pathlib import Path
root = str(Path(__file__).resolve().parent.parent)
theme = open(root + '/node_modules/tailwindcss/theme.css', encoding='utf-8').read()
val = dict(re.findall(r'--color-([a-z]+-\d+):\s*([^;]+);', theme))
HUES = ['red','orange','amber','yellow','lime','green','emerald','teal','cyan','sky','blue','indigo','violet','purple','fuchsia','pink','rose']
STEPS = [50,100,200,300,400,500,600,700,800,900,950]
# The greys: a ramp of our own rather than Tailwind's flipped, so the three
# surfaces stay apart (page darker than a card, a fill lighter than a card).
GREY = {50:'#15171a',100:'#2a2e33',200:'#363b41',300:'#4a5057',400:'#767c84',500:'#a0a6ad',
        600:'#b9bec4',700:'#cfd3d8',800:'#e2e5e8',900:'#eef0f2',950:'#f7f8f9'}
S = "html[data-theme='dark']:has([data-theme-area])"
out = []
w = out.append
w('/*')
w('  DARK MODE for the signed-in pages (Lawrence, 6 Nov 2026). GENERATED by')
w('  scripts/gen-dark-css.py from Tailwind\'s own palette; edit the script, not')
w('  this file, then re-run it: python scripts/gen-dark-css.py')
w('')
w('  How it works: Tailwind 4 draws every colour class from a CSS variable')
w('  (bg-neutral-100 is var(--color-neutral-100)), so dark mode swaps the')
w('  variables instead of giving 2,000 classes a dark: twin. The greys get a')
w('  dark ramp of their own; each hue is turned end over end (50 <-> 950,')
w('  100 <-> 900 ...), so a pale red warning with dark red words becomes a deep')
w('  red one with pale words and still reads as a warning.')
w('')
w('  It applies only when BOTH hold: the person chose Dark (ThemeSwitch sets')
w('  data-theme on <html>, kept in localStorage), and the page is a signed-in')
w('  one (Header renders the [data-theme-area] marker on /admin, /account and')
w('  /register). Public pages are always light. Screen only: printing from dark')
w('  mode prints the light sheet.')
w('')
w('  The exceptions below keep SOLID colours solid: a button with white words')
w('  (bg-brand, bg-red-700, the dark Staff Area button) must not turn pale.')
w('*/')
w('@media screen {')
w(f'  {S} {{')
w('    color-scheme: dark;')
for n in STEPS:
    w(f'    --color-neutral-{n}: {GREY[n]};')
for n in STEPS:
    w(f'    --color-gray-{n}: {GREY[n]};')
# Pink, rose and fuchsia turn a loud crimson when flipped (the Rooms &
# Cabins cards, 6 Nov 2026), so their pale fills are mixed halfway to the card.
SOFT = {'pink', 'rose', 'fuchsia'}
for h in HUES:
    for n in STEPS:
        flipped = val[f"{h}-{1000-n if n not in (50,950) else (950 if n==50 else 50)}"]
        if h in SOFT and n <= 200:
            flipped = f'color-mix(in oklab, {flipped} 50%, #1e2125)'
        w(f'    --color-{h}-{n}: {flipped};')
w('    --color-brand: #63b6bf;')
w('    --color-brand-dark: #93d2d9;')
w('    --color-brand-light: #173b40;')
w('    --dark-card: #1e2125;')
w('  }')
w('  /* keep-light: a part drawn dark in both modes (the footer) keeps its')
w('     light-mode colours. */')
w(f'  {S} .keep-light {{')
for n in STEPS:
    w(f'    --color-neutral-{n}: {val[f"neutral-{n}"]};')
for n in STEPS:
    w(f'    --color-gray-{n}: {val[f"gray-{n}"]};')
for h in HUES:
    for n in STEPS:
        w(f'    --color-{h}-{n}: {val[f"{h}-{n}"]};')
w('    --color-brand: #2a6f77;')
w('    --color-brand-dark: #1d4e54;')
w('    --color-brand-light: #e8f2f3;')
w('  }')
w(f'  {S} body {{')
w('    background-color: var(--dark-card);')
w('  }')
w('}')
w('')
w('/*')
w('  The class exceptions sit in the utilities layer, scoped with :where() so')
w('  they weigh exactly what the class itself weighs: they win over it by')
w('  coming later, and a hover:, disabled: or other variant on the same')
w('  element (which weighs more) still wins over them, as in light mode.')
w('  Unlayered, they beat every variant (code review, 6 Nov 2026).')
w('*/')
w('@layer utilities {')
w('  @media screen {')
W = f':where({S})'
def rule(sels, decls, ind='    '):
    for i, sel in enumerate(sels):
        w(f'{ind}{W} {sel}' + (',' if i < len(sels) - 1 else ' {'))
    for d in decls:
        w(f'{ind}  {d};')
    w(f'{ind}}}')
w('    /* White surfaces become the card colour (white itself stays white, for')
w('       the words on solid buttons). */')
rule(['.bg-white'], ['background-color: var(--dark-card)'])
for a in (95, 60):
    rule([f'.bg-white\\/{a}'], [f'background-color: color-mix(in oklab, var(--dark-card) {a}%, transparent)'])
rule(['.text-black'], ['color: var(--color-neutral-900)'])
w('    /* A pop-up (a menu, a dropdown) sits a shade above the card it opens')
w('       over: on dark a shadow alone does not lift it. */')
w('    /* Heavy rules (border-neutral-800 under print-sheet headings) would turn')
w('       near white; a mid grey keeps them a line, not a glare. */')
rule(['.border-neutral-700', '.border-neutral-800', '.border-neutral-900'], ['border-color: #5a6068'])
w('    /* The switch itself: drawn from <html>, which the head script sets')
w('       before paint, so it does not slide on after every page load. */')
rule(['.theme-switch-track'], ['background-color: #2a6f77'])
rule(['.theme-switch-knob'], ['transform: translateX(1rem)'])
rule(['.bg-white.shadow-lg', '.bg-white.shadow-xl'], ['background-color: var(--color-neutral-100)', 'border-color: var(--color-neutral-300)'])
w('    /* Solid fills under white words keep their light-mode colour. */')
keep = ['amber-500', 'amber-600', 'green-600', 'green-700', 'red-600', 'red-700']
for k in keep:
    rule([f'.bg-{k}'], [f'background-color: {val[k]}'])
for cls, col in (('neutral-700', '#4a5259'), ('neutral-800', '#3b4248'), ('neutral-900', '#2c3237')):
    rule([f'.bg-{cls}'], [f'background-color: {col}'])
rule(['.bg-brand', '.btn-primary'], ['background-color: #2a6f77'])
rule(['.bg-brand-dark'], ['background-color: #1d4e54'])
w('    /* "Cancel plan" (StaffPlanPanel) forces its red with bg-red-700!. */')
rule(['.bg-red-700\\!'], [f'background-color: {val["red-700"]} !important'])
w('    /* The navy words of the logo vanish on dark, so Header carries a copy')
w('       with the words light (Luke_14_Ministries_Logo_dark.png, the emblem')
w('       untouched); dark mode swaps which one shows. */')
rule(['.site-logo-light'], ['display: none'])
rule(['.site-logo-dark'], ['display: block'])
w('    /* Hovers, inside (hover: hover) as Tailwind puts its own. */')
w('    @media (hover: hover) {')
rule(['.hover\\:bg-white:hover'], ['background-color: var(--dark-card)'], '      ')
for k in keep:
    rule([f'.hover\\:bg-{k}:hover'], [f'background-color: {val[k]}'], '      ')
rule(['.btn-gold:hover'], [f'background-color: {val["amber-600"]}'], '      ')
rule(['.btn-primary:hover', '.hover\\:bg-brand-dark:hover'], ['background-color: #1d4e54'], '      ')
rule(['.hover\\:bg-brand:hover', '.btn-outline:hover'], ['background-color: #2a6f77', 'color: #fff'], '      ')
w('    }')
w('  }')
w('}')
open(root + '/app/theme-dark.css', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(out), 'lines')
